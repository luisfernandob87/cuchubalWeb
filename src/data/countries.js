export function detectCountryCode() {
  // 1) ubicación física aproximada por timezone del sistema
  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone || "";
    const segment = tz.split("/").pop();
    if (segment && TIMEZONE_DIAL[segment]) return TIMEZONE_DIAL[segment];
  } catch (_) {
    // seguir con locale
  }

  // 2) región del idioma del navegador (ej. es-GT)
  try {
    const locale = new Intl.Locale(navigator.language || "es");
    if (locale.region && locale.region.length === 2) {
      const found = COUNTRIES.find((c) => c.iso === locale.region.toUpperCase());
      if (found) return found.dial;
    }
  } catch (_) {
    // seguir con fallback de idioma
  }

  // 3) fallback por idioma
  const base = (navigator.language || "es").split("-")[0].toLowerCase();
  const fallbacks = { es: "+34", en: "+1", pt: "+55", fr: "+33", de: "+49", it: "+39" };
  return fallbacks[base] || "";
}